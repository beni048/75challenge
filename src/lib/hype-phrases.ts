/**
 * Hype phrases — the curated things people can say about someone's day.
 *
 * ONE POOL PER LANGUAGE, NOT TRANSLATIONS. This is a deliberate departure
 * from the EN/DE parity rule in start.md §11, and the reason is that humour
 * does not survive translation: "Built different" has no German equivalent
 * that is also funny, and forcing a 1:1 mapping produced German that read as
 * translated English. Each language therefore has its own independent list,
 * of its own length, written in that language.
 *
 * The German locale draws from BOTH `de` (High German) and `gsw` (Swiss
 * German) — the community is Swiss-led and the dialect lines are the funniest
 * ones in the set.
 *
 * A phrase is rendered IN THE LANGUAGE IT WAS SENT IN, never translated,
 * because it is a quote: it is what a specific person chose to say. That
 * matches how feed captions already work (start.md §5 — user-authored text is
 * shown as written). It is the same reason ids are stored rather than text:
 * the wording can be improved later without rewriting history.
 *
 * THE BAR FOR A PHRASE: it must read as unambiguous support at a glance, to
 * someone who is tired and having a hard day. Rejected on sight —
 *   - anything needing a parenthetical to clarify it is a compliment
 *     ("Genuinely unwell (complimentary)") — the disclaimer IS the tell;
 *   - backhanded praise ("You are making the rest of us look bad");
 *   - mental-health words used as intensifiers (insane, mental, unhinged);
 *   - anything implying the person is overdoing it or not resting;
 *   - vulgar intensifiers, however common in speech ("huere");
 *   - "beast" and similar, retired by start.md §14;
 *   - claims that are not true of this product (there is no leaderboard).
 * Numbering gaps below are deliberate: 43 phrases were removed against this
 * bar and their ids were NOT reused.
 *
 * IDS ARE PERMANENT. They are stored in daily_logs.hype_phrase_id. Never
 * renumber or reuse one; only ever append. Editing a phrase's `text` is fine.
 */

