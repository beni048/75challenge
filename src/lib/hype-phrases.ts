const BY_ID = new Map(HYPE_PHRASES.map((p) => [p.id, p]));

export function getHypePhrase(id: string): HypePhrase | undefined {
  return BY_ID.get(id);
}

/** Every phrase a given locale is allowed to draw from. */
export function phrasesForLocale(locale: Locale): HypePhrase[] {
  const pools = POOLS_FOR_LOCALE[locale] ?? POOLS_FOR_LOCALE.en;
  return HYPE_PHRASES.filter((p) => pools.includes(p.lang));
}

/**
 * Draws a phrase for this locale, never repeating `excludeId` — so re-rolling
 * always visibly changes the sentence rather than sometimes landing on the
 * same one and looking broken.
 */
export function pickRandomHypePhrase(locale: Locale, excludeId?: string | null): HypePhrase {
  const pool = phrasesForLocale(locale);
  const candidates = excludeId ? pool.filter((p) => p.id !== excludeId) : pool;
  // Only possible with a pool of one, which no locale has — but never throw.
  const list = candidates.length > 0 ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}

/**
 * The phrase as displayed. `vars` fills placeholders such as {days}; a phrase
 * that uses one and is rendered without it would show the raw braces, which
 * src/test/hype-phrases.test.ts guards against.
 */
export function localizedHypePhrase(
  phrase: HypePhrase,
  vars?: Record<string, string | number>
): string {
  return interpolate(phrase.text, vars);
}
